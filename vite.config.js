import { defineConfig } from 'vite';
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';

// Offline play / installable app: after the build, write dist/sw.js with the exact list of files to precache
// (hashed bundles, fonts, public/ files) and a cache name derived from their contents, so every deploy
// replaces the old cache. Pages are network-first (always the newest index when online), files cache-first.
function offline() {
  let outDir;
  return {
    name: 'horror-sword-offline',
    apply: 'build',
    configResolved(c) { outDir = path.resolve(c.root, c.build.outDir); },
    closeBundle() {
      const files = [];
      const walk = (dir) => {
        for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
          const p = path.join(dir, f.name);
          if (f.isDirectory()) walk(p);
          else if (f.name !== 'sw.js' && !f.name.endsWith('.map')) files.push(path.relative(outDir, p).split(path.sep).join('/'));
        }
      };
      walk(outDir);
      files.sort();
      const hash = createHash('sha1');
      for (const f of files) hash.update(f).update(fs.readFileSync(path.join(outDir, f)));
      const list = ['./', ...files.map((f) => './' + f)];
      fs.writeFileSync(path.join(outDir, 'sw.js'), `// generated by vite.config.js (offline plugin) — do not edit
const CACHE = 'horror-sword-${hash.digest('hex').slice(0, 12)}';
const FILES = ${JSON.stringify(list)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith('horror-sword-') && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  const keep = (res) => {
    if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
    return res;
  };
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).then(keep).catch(() => caches.match(req, { ignoreSearch: true }).then((r) => r || caches.match('./index.html'))));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).then(keep)));
});
`);
    },
  };
}

// Relative base: the build works from any subpath (GitHub Pages serves it at /horror-sword/),
// from a local static server, or opened from a zip, without hard-coding the repo name.
export default defineConfig({
  base: './',
  plugins: [offline()],
});
